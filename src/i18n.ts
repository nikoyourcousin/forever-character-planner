function readLocale(): Locale {
  if (typeof localStorage === 'undefined') return 'ru'
  return localStorage.getItem(LOCALE_KEY) === 'en' ? 'en' : 'ru'
}

export const locale = ref<Locale>(readLocale())

if (typeof document !== 'undefined') {
  document.documentElement.lang = locale.value
}

function lookup(bundle: unknown, key: string): string {
  const parts = key.split('.')
  let node: unknown = bundle
  for (const part of parts) {
    if (!node || typeof node !== 'object' || !(part in node)) return key
    node = (node as Record<string, unknown>)[part]
  }
  return typeof node === 'string' ? node : key
}

export function t(key: string): string {
  return lookup(dictionary[locale.value], key)
}

export function tf(key: string, vars: Record<string, string | number>): string {
  return t(key).replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''))
}

export function setLocale(next: Locale) {
  locale.value = next
  localStorage.setItem(LOCALE_KEY, next)
  document.documentElement.lang = next
}
